"""Оценка письменной работы рецензентом: восемь критериев по пять баллов, всего 40.

Взято из HINDAMISJUHEND 2025: 40% оценки это отзыв рецензента на письменную работу.
Каждый критерий оценивается от 5 до 1, и один балл в методичке означает прямо названное:
ученик выдал чужую работу за свою без ссылки или сдал текст, написанный текстовым роботом.
Баллы предлагает модель, решает учитель.
"""
MAX_SCORE = 40

CRITERIA = [
    (1, "Тема и исследовательский вопрос",
     "Тема актуальна, подход самостоятельный, тема по силам ученику и ему интересна, "
     "цель и задачи названы ясно, заголовок точен и отвечает содержанию."),
    (2, "Структура и построение работы",
     "Части работы идут в логичном порядке и соразмерны друг другу, работа выстроена вокруг "
     "исследовательского вопроса, заголовки отвечают содержанию, текст связный и доведён до конца."),
    (3, "Теоретическая часть",
     "Ученик разобрался в литературе, прежних исследованиях и взглядах по теме, они уместны "
     "и связаны с его собственной работой, а не пересказаны сами по себе."),
    (4, "Использованные источники",
     "Источники надёжные, их достаточно для темы, они разнообразны, ссылки стоят по тексту "
     "и список оформлен по правилам."),
    (5, "Язык работы и понятия",
     "Научный стиль без разговорных оборотов, понятия употреблены верно и объяснены, "
     "текст читается, ошибок мало."),
    (6, "Метод исследования",
     "Метод подходит вопросу, описан так, что работу можно повторить, выборка и ход работы понятны, "
     "ограничения метода названы."),
    (7, "Описание, анализ и выводы",
     "Результаты описаны и разобраны самим автором, он видит связи и объясняет их, "
     "выводы следуют из собранных данных и отвечают на исследовательский вопрос."),
    (8, "Оформление работы и приложений",
     "Оформление по правилам школы, таблицы, рисунки и приложения подписаны, пронумерованы "
     "и упомянуты в тексте, ссылки и список источников единообразны."),
]

SCALE = {
    5: "выполнено полностью и хорошо",
    4: "выполнено, есть отдельные мелкие недочёты",
    3: "есть заметные недочёты",
    2: "выполнено слабо, поверхностно или небрежно",
    1: "чужая работа выдана за свою без ссылки или сдан текст, написанный текстовым роботом",
}


def listing():
    """Критерии для запроса к модели."""
    return "\n".join(f"{n}. {name}: {what}" for n, name, what in CRITERIA) + "\n\nШкала:\n" + \
        "\n".join(f"{score} — {text}" for score, text in sorted(SCALE.items(), reverse=True))


def total(scores):
    """Сумма баллов по критериям, каждый от 1 до 5."""
    return sum(min(5, max(1, int(s))) for s in scores)


if __name__ == "__main__":
    assert len(CRITERIA) == 8 and MAX_SCORE == 8 * 5
    assert total([5] * 8) == MAX_SCORE and total([1] * 8) == 8
    assert total([9, 0, 3]) == 5 + 1 + 3  # чужие значения подрезаются, а не ломают отчёт
    assert "текстовым роботом" in listing()
    print("ok")
